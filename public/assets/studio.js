'use strict';

const pages = ['Dashboard', 'Categories', 'Topics', 'Storytelling', 'Hook Studio',
  'CTA Studio', 'Storyboard', 'Video Timeline', 'Brand Studio', 'Production',
  'Content Library', 'Media Assets', 'Engine', 'Diagnostics', 'Settings'];

const storageKey = 'tstudio-demo-v1';
const byId = (id) => document.getElementById(id);
const escape = (value) => String(value ?? '').replace(/[&<>"']/g, (character) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
}[character]));
const newId = () => globalThis.crypto?.randomUUID?.()
  ?? Date.now().toString(36) + Math.random().toString(36).slice(2);

const initialState = {
  categories: [
    { id: 'world', name: 'Coffee Around the World', description: 'Explore producing countries, culture and international trade.' },
    { id: 'culinary', name: 'Coffee & Culinary', description: 'Discover coffee as a culinary ingredient.' },
    { id: 'curiosity', name: 'Coffee Curiosities', description: 'Explore myths, traditions and unusual facts.' }
  ],
  topics: [],
  stories: [],
  hooks: [],
  ctas: [],
  scenes: []
};

function loadState() {
  try {
    return { ...structuredClone(initialState), ...JSON.parse(localStorage.getItem(storageKey)) };
  } catch {
    return structuredClone(initialState);
  }
}

let state = loadState();
let currentPage = 'Dashboard';
let selectedCategory = 'world';
let editing = null;

function saveState() {
  try {
    localStorage.setItem(storageKey, JSON.stringify(state));
  } catch {
    alert('Browser storage unavailable. Changes may be lost.');
  }
}

const definitions = {
  categories: [
    ['name', 'Name', 'text'],
    ['description', 'Editorial description', 'textarea']
  ],
  topics: [
    ['categoryId', 'Category', 'categories'],
    ['name', 'Title', 'text'],
    ['description', 'Description', 'textarea']
  ],
  stories: [
    ['topicId', 'Topic', 'topics'],
    ['title', 'Title', 'text'],
    ['angle', 'Narrative angle', 'text'],
    ['summary', 'Narrative', 'textarea'],
    ['facts', 'Facts to verify', 'textarea'],
    ['sources', 'Sources', 'textarea'],
    ['visual', 'Visual direction', 'textarea']
  ]
};

function navigate(page) {
  currentPage = page;
  render();
}

function renderCards(items, kind, extra = () => '') {
  if (!items.length) {
    return '<p>No items yet. Create one to get started.</p>';
  }

  return '<div class="grid">' + items.map((item) => `
    <article class="card">
      <h3>${escape(item.name ?? item.title ?? item.text)}</h3>
      <p>${escape(item.description ?? item.summary ?? '')}</p>
      ${extra(item)}
      <div class="actions">
        <button data-edit="${kind}" data-id="${escape(item.id)}">Edit</button>
        <button class="secondary" data-remove="${kind}" data-id="${escape(item.id)}">Delete</button>
      </div>
    </article>`).join('') + '</div>';
}

function categoryCards() {
  return renderCards(state.categories, 'categories', (item) =>
    `<button class="secondary" data-category="${escape(item.id)}">View topics</button>`);
}

function renderDashboard() {
  const metrics = [
    ['Categories', state.categories.length],
    ['Topics', state.topics.length],
    ['Stories', state.stories.length],
    ['Approved', state.stories.filter((story) => story.status === 'approved').length]
  ];

  return `<div class="grid">${metrics.map(([name, value]) =>
    `<article class="card"><div class="stat">${value}</div>${name}</article>`).join('')}
    </div><h2>Content categories</h2>${categoryCards()}
    <h2>Editorial workflow</h2>
    <article class="card">Category → Topic → Story → Hooks & CTAs → Storyboard → Production → Review</article>`;
}

function renderTopics() {
  if (!state.categories.some((category) => category.id === selectedCategory)) {
    selectedCategory = state.categories[0]?.id ?? '';
  }

  const options = state.categories.map((category) =>
    `<option value="${escape(category.id)}" ${category.id === selectedCategory ? 'selected' : ''}>${escape(category.name)}</option>`
  ).join('');

  return `<article class="card">
      <label for="categoryFilter">Category</label>
      <select id="categoryFilter">${options}</select>
      <div class="actions"><button id="seed" ${selectedCategory ? '' : 'disabled'}>Import sample coffee topics</button></div>
      <p class="muted">Curated sample catalog, not generated by AI.</p>
    </article><h2>Topics</h2>${renderCards(
      state.topics.filter((topic) => topic.categoryId === selectedCategory), 'topics'
    )}`;
}

function renderStories() {
  return renderCards(state.stories, 'stories', (story) => `
    <span class="badge">${escape(story.status ?? 'draft')}</span>
    <p><strong>Angle:</strong> ${escape(story.angle)}</p>
    <p><strong>Facts to verify:</strong> ${escape(story.facts)}</p>
    <p><strong>Sources:</strong> ${escape(story.sources)}</p>
    <p><strong>Visual direction:</strong> ${escape(story.visual)}</p>
    <button class="secondary" data-approve="${escape(story.id)}">
      ${story.status === 'approved' ? 'Return to draft' : 'Approve story'}
    </button>`);
}

function render() {
  byId('heading').textContent = currentPage === 'Dashboard' ? 'Editorial Dashboard' : currentPage;
  byId('nav').replaceChildren(...pages.map((page) => {
    const button = document.createElement('button');
    button.textContent = page;
    button.classList.toggle('active', page === currentPage);
    button.addEventListener('click', () => navigate(page));
    return button;
  }));

  const kind = { Dashboard: 'categories', Categories: 'categories', Topics: 'topics', Storytelling: 'stories' }[currentPage];
  byId('new').hidden = !kind;
  byId('new').textContent = ({ categories: '+ New category', topics: '+ New topic', stories: '+ New story' })[kind] ?? '+ New item';
  byId('new').onclick = () => openEditor(kind, {}, { categoryId: selectedCategory });

  const views = {
    Dashboard: renderDashboard,
    Categories: categoryCards,
    Topics: renderTopics,
    Storytelling: renderStories
  };

  byId('view').innerHTML = views[currentPage]?.()
    ?? `<article class="card"><h2>${escape(currentPage)}</h2><p>Planned module.</p></article>`;

  if (byId('categoryFilter')) {
    byId('categoryFilter').onchange = (event) => {
      selectedCategory = event.target.value;
      render();
    };
  }

  if (byId('seed')) {
    byId('seed').onclick = importTopics;
  }
}

async function importTopics() {
  if (!state.categories.some((category) => category.id === selectedCategory)) {
    return;
  }

  try {
    const response = await fetch('api.php?action=topics');
    if (!response.ok) throw new Error('Catalog request failed');
    const data = await response.json();

    for (const topic of data.topics) {
      if (!state.topics.some((item) => item.categoryId === selectedCategory && item.name === topic.title)) {
        state.topics.push({
          id: newId(),
          categoryId: selectedCategory,
          name: topic.title,
          description: topic.description
        });
      }
    }

    saveState();
    render();
  } catch {
    alert('Sample catalog unavailable.');
  }
}

function openEditor(kind, item = {}, defaults = {}) {
  if (!definitions[kind]) return;
  editing = { kind, item };
  byId('dialogtitle').textContent = item.id ? 'Edit item' : 'New item';

  byId('fields').innerHTML = definitions[kind].map(([name, label, type]) => {
    const value = item[name] ?? defaults[name] ?? '';
    let input;

    if (type === 'textarea') {
      input = `<textarea name="${name}" id="f-${name}">${escape(value)}</textarea>`;
    } else if (Array.isArray(state[type])) {
      input = `<select required name="${name}" id="f-${name}">${state[type].map((option) =>
        `<option value="${escape(option.id)}" ${option.id === value ? 'selected' : ''}>${escape(option.name ?? option.title)}</option>`
      ).join('')}</select>`;
    } else {
      input = `<input required name="${name}" id="f-${name}" value="${escape(value)}">`;
    }

    return `<label for="f-${name}">${label}</label>${input}`;
  }).join('');

  byId('editor').showModal();
}

byId('close').onclick = () => byId('editor').close();

byId('editform').onsubmit = (event) => {
  event.preventDefault();
  const { kind, item } = editing;
  const values = Object.fromEntries(new FormData(event.target));

  for (const [name, , type] of definitions[kind]) {
    if (Array.isArray(state[type]) && !state[type].some((option) => option.id === values[name])) {
      alert('Create the related item first.');
      return;
    }
    if (type === 'text' && !values[name].trim()) {
      alert('A required field is empty.');
      return;
    }
  }

  const updated = { ...item, ...values, id: item.id ?? newId() };
  if (kind === 'stories') updated.status = 'draft';
  state[kind] = item.id
    ? state[kind].map((entry) => entry.id === item.id ? updated : entry)
    : [...state[kind], updated];

  saveState();
  byId('editor').close();
  render();
};

document.addEventListener('click', (event) => {
  const button = event.target.closest('button');
  if (!button) return;
  const { edit, remove, category, id, approve } = button.dataset;

  if (category) {
    selectedCategory = category;
    navigate('Topics');
  }

  if (edit) {
    const item = state[edit]?.find((entry) => entry.id === id);
    if (item) openEditor(edit, item);
  }

  if (approve) {
    const story = state.stories.find((entry) => entry.id === approve);
    if (story) {
      story.status = story.status === 'approved' ? 'draft' : 'approved';
      saveState();
      render();
    }
  }

  if (remove) {
    if (remove === 'topics' && state.stories.some((story) => story.topicId === id)) {
      alert('Remove related stories first.');
      return;
    }
    if (remove === 'categories' && state.topics.some((topic) => topic.categoryId === id)) {
      alert('Remove related topics first.');
      return;
    }
    if (confirm('Delete this draft item?')) {
      state[remove] = state[remove].filter((entry) => entry.id !== id);
      saveState();
      render();
    }
  }
});

render();
